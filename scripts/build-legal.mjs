// build-legal.mjs — generates the SMS/voice program legal pages:
//   EN: /privacy/  /terms/      ES: /privacidad/  /terminos/
//
// These pages exist primarily to satisfy carrier requirements for the
// A2P 10DLC campaign behind the rcsd.info text/voice lines
// (EN (650) 482-8912, ES (650) 399-7203): the campaign registration links to
// /privacy/ and /terms/, and carrier reviewers verify the URLs resolve and
