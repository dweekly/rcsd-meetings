// "msg & data rates", HELP/STOP, support contact, no-marketing-share pledge).

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { headMeta, siteNav, siteFooter } from './html-parts.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DOCS = path.join(__dirname, '..', 'docs');

const PAGE_CSS = `
.legal-wrap { max-width: 760px; margin: 0 auto; padding: 2rem 1.25rem 4rem; }
.legal-wrap h1 { font-family: 'Fraunces', serif; margin-bottom: .25rem; }
.legal-wrap .updated { color: #5a6b5d; font-size: .9rem; margin-bottom: 2rem; }
.legal-wrap h2 { font-family: 'Fraunces', serif; margin: 2rem 0 .5rem; font-size: 1.25rem; }
.legal-wrap p, .legal-wrap li { line-height: 1.6; }
.legal-wrap ul { padding-left: 1.25rem; }
`;

const UPDATED = '2026-07-19';

function page({ lang, title, description, canonical, altLangHref, bodyHtml }) {
  return `<!DOCTYPE html>
<html lang="${lang}">
<head>
${headMeta({
    title,
    description,
    canonical,
    ogLocale: lang === 'es' ? 'es_US' : 'en_US',
    hreflang: [
      { lang: lang === 'es' ? 'en' : 'es', href: altLangHref },
    ],
    pageCSS: PAGE_CSS,
  })}
</head>
<body>
${siteNav({ activePage: null, lang, altLangHref })}
<main class="legal-wrap">
${bodyHtml}
</main>
${siteFooter({ lang })}
</body>
</html>
`;
}

